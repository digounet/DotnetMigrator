    public static PackageModernizationRule? Find(string packageId)
    {
        if (ById.TryGetValue(packageId, out var rule)) return rule;
        foreach (var (prefix, prefixRule) in ByPrefix)
            if (packageId.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)) return prefixRule;
        return null;
    }
